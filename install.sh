#!/usr/bin/env bash
# Install the skills, agents and profiles of this repository into agent hosts.
# Usage: install.sh [--project DIR] [--dry-run] [--uninstall]
#   default        skills   ~/.agents/skills/<name> (Codex, omp, others) and ~/.claude/skills/<name>
#                  agents   ~/.claude/agents/<role>.md, ~/.omp/agent/agents/<role>.md (links),
#                           ~/.codex/agents/<role>.toml (generated from agents/<role>.md)
#                  profiles ${XDG_CONFIG_HOME:-~/.config}/maintainer-skills/profiles/<owner>__<repo>.md
#   --project DIR  DIR/.agents/skills/<name> and DIR/.claude/skills/<name> only (relative links if DIR
#                  contains this repo, absolute otherwise)
#   --dry-run      print what would change
#   --uninstall    remove what this script installed
# Existing files that this repo did not install are reported and left alone. Re-run after pulling.
set -euo pipefail

usage() { sed -n '2,13p' "$0" | sed 's/^# \{0,1\}//'; }
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
project=""; dry=0; uninstall=0
while [ $# -gt 0 ]; do
  case "$1" in
    --project) project="${2:?--project needs a directory}"; shift ;;
    --dry-run) dry=1 ;;
    --uninstall) uninstall=1 ;;
    -h|--help) usage; exit 0 ;;
    *) echo "unknown argument: $1" >&2; usage >&2; exit 2 ;;
  esac
  shift
done

run() { if [ $dry = 1 ]; then echo "would: $*"; else "$@"; fi; }

# link SRC DEST: create or refresh DEST -> SRC unless DEST is foreign.
link() {
  local src="$1" dest="$2" cur
  if [ -L "$dest" ]; then
    cur="$(readlink -f "$dest" 2>/dev/null || true)"
    if [ "$cur" != "$(readlink -f "$src")" ] && [ -e "$dest" ] && [[ "$cur" != "$here"/* ]]; then
      echo "skip $dest: links to $cur (not this repo)"; return
    fi
  elif [ -e "$dest" ]; then
    echo "skip $dest: exists and is not a symlink"; return
  fi
  if [ $uninstall = 1 ]; then
    [ -L "$dest" ] && { run rm -f "$dest"; [ $dry = 1 ] || echo "removed $dest"; }
    return
  fi
  run mkdir -p "$(dirname "$dest")"
  run ln -sfn "$src" "$dest"
  [ $dry = 1 ] || echo "linked $dest -> $src"
}

# Codex custom agents are TOML (name, description, developer_instructions), so they are generated.
marker="# Generated by maintainer-skills install.sh from"
codex_agent() {
  local md="$1" dest="$2" name desc body
  if [ -e "$dest" ] && ! head -1 "$dest" | grep -qF "$marker"; then
    echo "skip $dest: exists and was not generated by this repo"; return
  fi
  if [ $uninstall = 1 ]; then
    [ -e "$dest" ] && { run rm -f "$dest"; [ $dry = 1 ] || echo "removed $dest"; }
    return
  fi
  name="$(awk 'NR==1{next} /^---$/{exit} sub(/^name: */,"")' "$md")"
  desc="$(awk 'NR==1{next} /^---$/{exit} sub(/^description: */,"")' "$md")"
  body="$(awk 'f>=2{print; next} /^---$/{f++}' "$md")"
  if [[ "$body" == *"'''"* ]]; then echo "skip $dest: $md contains ''' (not representable)" >&2; return; fi
  if [ $dry = 1 ]; then echo "would: write $dest"; return; fi
  mkdir -p "$(dirname "$dest")"
  {
    echo "$marker ${md#"$here"/}; edits are overwritten."
    printf 'name = %s\n' "$(jq -Rn --arg v "${name//-/_}" '$v')"
    printf 'description = %s\n' "$(jq -Rn --arg v "$desc" '$v')"
    printf "developer_instructions = '''\n%s\n'''\n" "$body"
  } > "$dest"
  echo "wrote $dest"
}

skills=()
for d in "$here"/skills/*/; do [ -f "$d/SKILL.md" ] && skills+=("$(basename "$d")"); done

if [ -n "$project" ]; then
  [ -d "$project" ] || { echo "install.sh: --project $project: not a directory" >&2; exit 2; }
  project="$(cd "$project" && pwd)"
  for s in "${skills[@]}"; do
    for host in .agents/skills .claude/skills; do
      dest="$project/$host/$s"
      if [[ "$here" == "$project"/* ]]; then
        src="$(realpath --relative-to="$project/$host" "$here/skills/$s")"
        link "$src" "$dest"
      else
        link "$here/skills/$s" "$dest"
      fi
    done
  done
  exit 0
fi

for s in "${skills[@]}"; do
  link "$here/skills/$s" "$HOME/.agents/skills/$s"
  link "$here/skills/$s" "$HOME/.claude/skills/$s"
done
for a in "$here"/agents/*.md; do
  [ -f "$a" ] || continue
  role="$(basename "$a" .md)"
  link "$a" "$HOME/.claude/agents/$role.md"
  link "$a" "$HOME/.omp/agent/agents/$role.md"
  codex_agent "$a" "${CODEX_HOME:-$HOME/.codex}/agents/$role.toml"
done
cfg="${XDG_CONFIG_HOME:-$HOME/.config}/maintainer-skills/profiles"
for p in "$here"/profiles/*__*.md; do
  [ -f "$p" ] && link "$p" "$cfg/$(basename "$p")"
done
exit 0
