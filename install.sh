#!/usr/bin/env bash
# Install the skills, agents and profiles of this repository into agent hosts.
# Usage: install.sh [--project DIR] [--dry-run] [--uninstall] [--check]
#   default        skills   ~/.agents/skills/<name> (Codex, omp, others) and ~/.claude/skills/<name>
#                  agents   ~/.claude/agents/<role>.md, ~/.omp/agent/agents/<role>.md (links),
#                           ~/.codex/agents/<role>.toml (generated from agents/<role>.md)
#                  profiles ${XDG_CONFIG_HOME:-~/.config}/maintainer-skills/profiles/<owner>__<repo>.md
#   --project DIR  DIR/.agents/skills/<name> and DIR/.claude/skills/<name> only (relative links if DIR
#                  contains this repo, absolute otherwise)
#   --dry-run      print what would change
#   --uninstall    remove what this script installed
#   --check        change nothing; list items that are missing, stale (a link pointing elsewhere or at a
#                  removed file, a Codex TOML generated from an older agents/<role>.md) or foreign; exit 1
#                  if there are any
# Existing files that this repo did not install are reported and left alone. Re-run after pulling.
set -euo pipefail

usage() { sed -n '2,16p' "$0" | sed 's/^# \{0,1\}//'; }
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
project=""; dry=0; uninstall=0; check=0; problems=0
while [ $# -gt 0 ]; do
  case "$1" in
    --project) project="${2:?--project needs a directory}"; shift ;;
    --dry-run) dry=1 ;;
    --uninstall) uninstall=1 ;;
    --check) check=1 ;;
    -h|--help) usage; exit 0 ;;
    *) echo "unknown argument: $1" >&2; usage >&2; exit 2 ;;
  esac
  shift
done
[ $((check + uninstall)) -le 1 ] || { echo "--check and --uninstall exclude each other" >&2; exit 2; }

run() { if [ $dry = 1 ]; then echo "would: $*"; else "$@"; fi; }
problem() { echo "$1"; problems=$((problems + 1)); }
sha256() { if command -v sha256sum >/dev/null; then sha256sum "$1" | cut -c1-64; else shasum -a 256 "$1" | cut -c1-64; fi; }

# link SRC DEST: create or refresh DEST -> SRC unless DEST is foreign.
link() {
  local src="$1" dest="$2" cur want
  if [ $check = 1 ]; then
    case "$src" in /*) want="$(readlink -f "$src")" ;; *) want="$(realpath -m "$(dirname "$dest")/$src")" ;; esac
    if [ -L "$dest" ]; then
      cur="$(readlink -f "$dest" 2>/dev/null || true)"
      [ "$cur" = "$want" ] || problem "stale $dest: links to $(readlink "$dest"), expected $src"
    elif [ -e "$dest" ]; then problem "foreign $dest: exists and is not a symlink"
    else problem "missing $dest"; fi
    return
  fi
  if [ -L "$dest" ]; then
    cur="$(readlink -f "$dest" 2>/dev/null || true)"
    if [ "$cur" != "$(readlink -f "$src")" ] && [ -e "$dest" ] && [[ "$cur" != "$here"/* ]]; then
      echo "skip $dest: links to $cur (not this repo)"; return
    fi
  elif [ -e "$dest" ]; then
    echo "skip $dest: exists and is not a symlink"; return
  fi
  if [ $uninstall = 1 ]; then
    [ -L "$dest" ] && { run rm -f "$dest"; [ $dry = 1 ] || echo "removed $dest"; }
    return
  fi
  run mkdir -p "$(dirname "$dest")"
  run ln -sfn "$src" "$dest"
  [ $dry = 1 ] || echo "linked $dest -> $src"
}

# Codex custom agents are TOML (name, description, developer_instructions), so they are generated. The
# marker line carries the sha256 of the source, so --check can tell a TOML generated before a pull.
marker="# Generated by maintainer-skills install.sh from"
codex_agent() {
  local md="$1" dest="$2" name desc body sum
  sum="$(sha256 "$md")"
  if [ $check = 1 ]; then
    if [ ! -e "$dest" ]; then problem "missing $dest"
    elif ! head -1 "$dest" | grep -qF "$marker"; then problem "foreign $dest: not generated by this repo"
    elif ! head -1 "$dest" | grep -qF "(sha256 $sum)"; then problem "stale $dest: generated from an older ${md#"$here"/}"
    fi
    return
  fi
  if [ -e "$dest" ] && ! head -1 "$dest" | grep -qF "$marker"; then
    echo "skip $dest: exists and was not generated by this repo"; return
  fi
  if [ $uninstall = 1 ]; then
    [ -e "$dest" ] && { run rm -f "$dest"; [ $dry = 1 ] || echo "removed $dest"; }
    return
  fi
  name="$(awk 'NR==1{next} /^---$/{exit} sub(/^name: */,"")' "$md")"
  desc="$(awk 'NR==1{next} /^---$/{exit} sub(/^description: */,"")' "$md")"
  body="$(awk 'f>=2{print; next} /^---$/{f++}' "$md")"
  if [[ "$body" == *"'''"* ]]; then echo "skip $dest: $md contains ''' (not representable)" >&2; return; fi
  if [ $dry = 1 ]; then echo "would: write $dest"; return; fi
  mkdir -p "$(dirname "$dest")"
  {
    echo "$marker ${md#"$here"/} (sha256 $sum); edits are overwritten."
    printf 'name = %s\n' "$(jq -Rn --arg v "${name//-/_}" '$v')"
    printf 'description = %s\n' "$(jq -Rn --arg v "$desc" '$v')"
    printf "developer_instructions = '''\n%s\n'''\n" "$body"
  } > "$dest"
  echo "wrote $dest"
}

# --check: links in the install directories that point into this repo at a file that no longer exists
# (a skill, agent or profile that was renamed or removed), and Codex TOML generated from a removed agent.
leftovers() {
  local d f t src
  for d in "$@"; do
    [ -d "$d" ] || continue
    for f in "$d"/*; do
      if [ -L "$f" ]; then
        t="$(readlink "$f")"; case "$t" in /*) ;; *) t="$(realpath -m "$d/$t")" ;; esac
        [[ "$t" == "$here"/* ]] && [ ! -e "$t" ] && problem "stale $f: points at removed ${t#"$here"/}; remove it by hand"
      elif [[ "$f" == *.toml ]] && head -1 "$f" 2>/dev/null | grep -qF "$marker"; then
        src="$(head -1 "$f" | sed -n "s|^$marker \([^ ]*\) .*|\1|p")"
        [ -n "$src" ] && [ ! -e "$here/$src" ] && problem "stale $f: generated from removed $src; remove it by hand"
      fi
    done
  done
  return 0
}

finish() {
  if [ $check = 1 ]; then
    if [ $problems -gt 0 ]; then echo "$problems item(s) need attention; run install.sh to refresh"; exit 1; fi
    echo "all installed items are current"
  fi
  exit 0
}

skills=()
for d in "$here"/skills/*/; do [ -f "$d/SKILL.md" ] && skills+=("$(basename "$d")"); done

if [ -n "$project" ]; then
  [ -d "$project" ] || { echo "install.sh: --project $project: not a directory" >&2; exit 2; }
  project="$(cd "$project" && pwd)"
  for s in "${skills[@]}"; do
    for host in .agents/skills .claude/skills; do
      dest="$project/$host/$s"
      if [[ "$here" == "$project"/* ]]; then
        src="$(realpath --relative-to="$project/$host" "$here/skills/$s")"
        link "$src" "$dest"
      else
        link "$here/skills/$s" "$dest"
      fi
    done
  done
  [ $check = 0 ] || leftovers "$project/.agents/skills" "$project/.claude/skills"
  finish
fi

codex_dir="${CODEX_HOME:-$HOME/.codex}/agents"
cfg="${XDG_CONFIG_HOME:-$HOME/.config}/maintainer-skills/profiles"
for s in "${skills[@]}"; do
  link "$here/skills/$s" "$HOME/.agents/skills/$s"
  link "$here/skills/$s" "$HOME/.claude/skills/$s"
done
for a in "$here"/agents/*.md; do
  [ -f "$a" ] || continue
  role="$(basename "$a" .md)"
  link "$a" "$HOME/.claude/agents/$role.md"
  link "$a" "$HOME/.omp/agent/agents/$role.md"
  codex_agent "$a" "$codex_dir/$role.toml"
done
for p in "$here"/profiles/*__*.md; do
  [ -f "$p" ] && link "$p" "$cfg/$(basename "$p")"
done
[ $check = 0 ] || leftovers "$HOME/.agents/skills" "$HOME/.claude/skills" "$HOME/.claude/agents" \
                            "$HOME/.omp/agent/agents" "$codex_dir" "$cfg"
finish
